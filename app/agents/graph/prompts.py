from dotenv import load_dotenv

load_dotenv()

# 评估专用严格模式：关闭推荐/建议/追问，避免干扰 RAG 指标
EVAL_STRICT = os.getenv("AGENT_EVAL_STRICT", "true").lower() == "true"

# 汇总输出模式：stream=流式自然语言（默认）；structured=with_structured_output 强约束
SUMMARY_MODE = os.getenv("AGENT_SUMMARY_MODE", "stream").strip().lower()


