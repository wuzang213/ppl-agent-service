def daily_system() -> str:
    from datetime import datetime

    now = datetime.now().strftime("%Y-%m-%d %H:%M %A")
    return DAILY_SYSTEM.format(now=now)


def history_summary_system() -> str:
    return HISTORY_SUMMARY_SYSTEM


def summary_system() -> str:
    base = SUMMARY_SYSTEM_JSON if SUMMARY_MODE == "structured" else SUMMARY_SYSTEM
    if EVAL_STRICT:
        base += _STRICT_RULES
    return base
